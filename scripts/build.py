#!/usr/bin/env python3
"""Generates Claude Code and Codex agents from roles/*.md.

The source of truth is roles/<role>.md (frontmatter: name, description, color and an
optional extra_tools) plus roles/_common.md, which is appended to every role. Every
agent defaults to the cheap tier; the producer picks the model and effort per run from
tools/budget.py routing.

Claude agents get an explicit tool list. Without it a subagent inherits every tool of
the session, and with them the list of all the user's skills and MCP tools: a probe run
started at 21.9K tokens with inherited tools and at 7.6K with this list
(scripts/probe_overhead.py). An explicit effort keeps agents off the session's effort.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES_DIR = ROOT / "roles"
CLAUDE_AGENTS_DIR = ROOT / "plugins" / "game-studio" / "agents"
CODEX_AGENTS_DIR = ROOT / "codex" / "agents"

CLAUDE_DEFAULT_MODEL = "sonnet"
CLAUDE_DEFAULT_EFFORT = "medium"
CLAUDE_TOOLS = ("Read", "Write", "Edit", "Bash", "Glob", "Grep")
CODEX_DEFAULT_EFFORT = "medium"
REQUIRED_KEYS = ("name", "description", "color")
OPTIONAL_KEYS = ("extra_tools",)


def parse_role(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: no frontmatter")
    header, body = text[4:].split("\n---\n", 1)
    meta = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    missing = [key for key in REQUIRED_KEYS if not meta.get(key)]
    if missing:
        raise ValueError(f"{path}: missing fields {', '.join(missing)}")
    extra = [key for key in meta if key not in REQUIRED_KEYS + OPTIONAL_KEYS]
    if extra:
        raise ValueError(f"{path}: unknown fields {', '.join(extra)}")
    if meta["name"] != path.stem:
        raise ValueError(f"{path}: name does not match the file name")
    # description goes into YAML unquoted, so ": " and " #" would break the frontmatter.
    if ": " in meta["description"] or " #" in meta["description"]:
        raise ValueError(f"{path}: description must not contain ': ' or ' #'")
    return meta, body.strip()


def instructions(body: str, common: str) -> str:
    return f"{body}\n\n{common}\n"


def claude_tools(meta: dict) -> str:
    extra = [tool.strip() for tool in meta.get("extra_tools", "").split(",") if tool.strip()]
    return ", ".join(CLAUDE_TOOLS + tuple(tool for tool in extra if tool not in CLAUDE_TOOLS))


def claude_agent(meta: dict, body: str, common: str) -> str:
    return (
        "---\n"
        f"name: {meta['name']}\n"
        f"description: {meta['description']}\n"
        f"model: {CLAUDE_DEFAULT_MODEL}\n"
        f"effort: {CLAUDE_DEFAULT_EFFORT}\n"
        f"color: {meta['color']}\n"
        f"tools: {claude_tools(meta)}\n"
        "---\n\n"
        f"<!-- Generated by scripts/build.py from roles/{meta['name']}.md -->\n\n"
        f"{instructions(body, common)}"
    )


def toml_basic_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def codex_agent(meta: dict, body: str, common: str) -> str:
    text = instructions(body, common)
    # A TOML literal multi-line string has no escapes, so backslashes and quotes
    # in the prompt arrive unchanged.
    if "'''" in text:
        raise ValueError(f"roles/{meta['name']}.md: text contains ''' which breaks the TOML literal string")
    return (
        f"# Generated by scripts/build.py from roles/{meta['name']}.md — do not edit by hand\n"
        f"name = {toml_basic_string('studio-' + meta['name'])}\n"
        f"description = {toml_basic_string(meta['description'])}\n"
        f"model_reasoning_effort = {toml_basic_string(CODEX_DEFAULT_EFFORT)}\n"
        f"developer_instructions = '''\n{text}'''\n"
    )


def expected_files() -> dict[Path, str]:
    common = (ROLES_DIR / "_common.md").read_text(encoding="utf-8").strip()
    files = {}
    for role_path in sorted(ROLES_DIR.glob("*.md")):
        if role_path.name.startswith("_"):
            continue
        meta, body = parse_role(role_path)
        files[CLAUDE_AGENTS_DIR / f"{meta['name']}.md"] = claude_agent(meta, body, common)
        files[CODEX_AGENTS_DIR / f"studio-{meta['name']}.toml"] = codex_agent(meta, body, common)
    return files


def stale_files(expected: dict[Path, str]) -> list[Path]:
    existing = list(CLAUDE_AGENTS_DIR.glob("*.md")) + list(CODEX_AGENTS_DIR.glob("*.toml"))
    return sorted(path for path in existing if path not in expected)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build agents from roles/*.md")
    parser.add_argument("--check", action="store_true", help="only check that the generated files are up to date")
    args = parser.parse_args()

    expected = expected_files()
    stale = stale_files(expected)
    outdated = [
        path for path, content in expected.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]

    if args.check:
        for path in outdated:
            print(f"outdated: {path.relative_to(ROOT)}")
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}")
        if outdated or stale:
            print("Run: python3 scripts/build.py")
            return 1
        print(f"OK: {len(expected)} agent files are up to date")
        return 0

    CLAUDE_AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    CODEX_AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    for path in outdated:
        path.write_text(expected[path], encoding="utf-8")
        print(f"written: {path.relative_to(ROOT)}")
    for path in stale:
        path.unlink()
        print(f"removed: {path.relative_to(ROOT)}")
    print(f"Done: {len(expected)} agent files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
